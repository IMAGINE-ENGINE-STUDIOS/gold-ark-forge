import { useState, useEffect } from 'react';
import Header from '@/components/Header';
import Footer from '@/components/Footer';
import { getForecastLog, clearForecastLog, type ForecastLogEntry, biasToRainbowColor } from '@/lib/forecastLog';
import { Trash2, TrendingUp, TrendingDown, Minus, RefreshCw, BarChart3 } from 'lucide-react';
import { Link } from 'react-router-dom';

const DirectionIcon = ({ direction }: { direction: string }) => {
  if (direction === 'bullish') return <TrendingUp className="w-3.5 h-3.5 text-emerald-400" />;
  if (direction === 'bearish') return <TrendingDown className="w-3.5 h-3.5 text-red-400" />;
  return <Minus className="w-3.5 h-3.5 text-marble/40" />;
};

const AngleIndicator = ({ angle, color }: { angle: number; color: string }) => (
  <div className="relative w-8 h-8 flex items-center justify-center">
    <div className="absolute inset-0 rounded-full border border-gold/10" />
    <div
      className="w-4 h-0.5 rounded-full origin-left"
      style={{
        backgroundColor: color,
        transform: `rotate(${-angle}deg)`,
        boxShadow: `0 0 6px ${color}`,
      }}
    />
  </div>
);

const LogRegistry = () => {
  const [log, setLog] = useState<ForecastLogEntry[]>([]);
  const [filter, setFilter] = useState('');

  useEffect(() => {
    setLog(getForecastLog());
  }, []);

  const refresh = () => setLog(getForecastLog());

  const handleClear = () => {
    if (confirm('Clear all forecast logs?')) {
      clearForecastLog();
      setLog([]);
    }
  };

  const filtered = filter
    ? log.filter(e => e.symbol.toLowerCase().includes(filter.toLowerCase()) || e.category.toLowerCase().includes(filter.toLowerCase()))
    : log;

  return (
    <div className="min-h-screen bg-navy">
      <Header />

      <div className="container mx-auto px-6 py-12">
        {/* Hero */}
        <div className="text-center mb-10">
          <div className="divider-ornate mb-4">
            <span className="font-display text-[10px] tracking-[0.4em] text-gold/60">ANALYTICS</span>
          </div>
          <h1 className="font-display text-3xl md:text-4xl text-marble tracking-[0.05em] mb-3">
            FORECAST <span className="text-gradient-gold">LOG REGISTRY</span>
          </h1>
          <p className="text-marble/40 text-sm max-w-lg mx-auto font-body">
            Historical record of all forecast projections generated by the GALIVE engine.
            Each entry captures the indicator snapshot, directional bias, and rainbow angle at the moment of projection.
          </p>
        </div>

        {/* Controls */}
        <div className="flex items-center justify-between mb-6 gap-4 flex-wrap">
          <div className="flex items-center gap-3">
            <input
              type="text"
              value={filter}
              onChange={(e) => setFilter(e.target.value)}
              placeholder="Filter by symbol or category…"
              className="bg-navy-light border border-gold/20 text-marble text-sm rounded px-3 py-1.5 font-mono placeholder:text-marble/20 focus:outline-none focus:border-gold/40 w-64"
            />
            <span className="text-[10px] font-mono text-marble/30">{filtered.length} entries</span>
          </div>
          <div className="flex items-center gap-2">
            <Link
              to="/trading-bridge"
              className="flex items-center gap-1.5 px-3 py-1.5 rounded border border-gold/20 text-marble/50 hover:text-gold hover:border-gold/40 transition-all text-[10px] font-display tracking-wider"
            >
              <BarChart3 className="w-3 h-3" /> SWAP
            </Link>
            <button onClick={refresh} className="flex items-center gap-1 px-3 py-1.5 rounded border border-gold/20 text-marble/50 hover:text-gold hover:border-gold/40 transition-all text-[10px] font-display tracking-wider">
              <RefreshCw className="w-3 h-3" /> REFRESH
            </button>
            <button onClick={handleClear} className="flex items-center gap-1 px-3 py-1.5 rounded border border-red-500/20 text-red-400/50 hover:text-red-400 hover:border-red-500/40 transition-all text-[10px] font-display tracking-wider">
              <Trash2 className="w-3 h-3" /> CLEAR ALL
            </button>
          </div>
        </div>

        {/* Table */}
        {filtered.length === 0 ? (
          <div className="text-center py-20">
            <BarChart3 className="w-12 h-12 text-gold/20 mx-auto mb-4" />
            <p className="text-marble/30 font-display text-sm tracking-wider">NO FORECAST ENTRIES YET</p>
            <p className="text-marble/15 text-xs font-mono mt-2">Toggle the FORECAST button on the Swap chart to generate entries</p>
          </div>
        ) : (
          <div className="rounded-lg border border-gold/15 overflow-hidden">
            {/* Header */}
            <div className="grid grid-cols-[40px_1fr_80px_80px_100px_100px_60px_80px_1fr] gap-2 px-4 py-2 bg-navy-dark/60 border-b border-gold/10 text-[8px] font-display tracking-[0.15em] text-marble/30">
              <span>ANGLE</span>
              <span>SYMBOL</span>
              <span>TF</span>
              <span>DIRECTION</span>
              <span>PRICE</span>
              <span>PROJECTED</span>
              <span>BIAS</span>
              <span>TIME</span>
              <span className="hidden lg:block">INDICATORS</span>
            </div>

            {/* Rows */}
            <div className="max-h-[60vh] overflow-y-auto">
              {filtered.map((entry) => (
                <div
                  key={entry.id}
                  className="grid grid-cols-[40px_1fr_80px_80px_100px_100px_60px_80px_1fr] gap-2 px-4 py-2.5 border-b border-gold/5 hover:bg-gold/5 transition-colors items-center"
                >
                  <AngleIndicator angle={entry.angle} color={entry.color} />
                  <div className="flex items-center gap-2 min-w-0">
                    <span className="font-mono text-xs text-marble truncate">{entry.symbol}</span>
                    <span className="text-[8px] text-marble/20 font-display tracking-wider uppercase">{entry.category}</span>
                  </div>
                  <span className="text-[10px] font-mono text-gold/60">{entry.timeframe}</span>
                  <div className="flex items-center gap-1">
                    <DirectionIcon direction={entry.direction} />
                    <span className={`text-[9px] font-mono ${
                      entry.direction === 'bullish' ? 'text-emerald-400' : entry.direction === 'bearish' ? 'text-red-400' : 'text-marble/40'
                    }`}>
                      {entry.direction.toUpperCase()}
                    </span>
                  </div>
                  <span className="text-[10px] font-mono text-marble/60">${entry.currentPrice < 10 ? entry.currentPrice.toFixed(4) : entry.currentPrice.toLocaleString('en-US', { minimumFractionDigits: 2 })}</span>
                  <span className="text-[10px] font-mono" style={{ color: entry.color }}>
                    ${entry.projectedPrice < 10 ? entry.projectedPrice.toFixed(4) : entry.projectedPrice.toLocaleString('en-US', { minimumFractionDigits: 2 })}
                  </span>
                  <div className="flex items-center gap-1">
                    <div className="w-6 h-1.5 rounded-full overflow-hidden bg-navy-light/50">
                      <div
                        className="h-full rounded-full"
                        style={{
                          width: `${((entry.bias + 1) / 2) * 100}%`,
                          backgroundColor: entry.color,
                        }}
                      />
                    </div>
                    <span className="text-[8px] font-mono text-marble/25">{entry.bias.toFixed(2)}</span>
                  </div>
                  <span className="text-[9px] font-mono text-marble/25">
                    {new Date(entry.timestamp).toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit' })}
                  </span>
                  <div className="hidden lg:flex items-center gap-2 text-[8px] font-mono text-marble/20">
                    <span>RSI:{entry.indicators.rsi.toFixed(0)}</span>
                    <span>SMA:{entry.indicators.sma20 < 10 ? entry.indicators.sma20.toFixed(2) : Math.round(entry.indicators.sma20)}</span>
                    <span className={entry.indicators.macdCross === 'bullish' ? 'text-emerald-400/40' : 'text-red-400/40'}>
                      MACD:{entry.indicators.macdCross === 'bullish' ? '▲' : '▼'}
                    </span>
                  </div>
                </div>
              ))}
            </div>
          </div>
        )}

        {/* Legend */}
        <div className="mt-8 flex items-center justify-center gap-6 flex-wrap">
          <div className="flex items-center gap-2">
            <div className="w-16 h-2 rounded-full" style={{ background: 'linear-gradient(to right, hsl(0,80%,55%), hsl(30,80%,55%), hsl(60,80%,55%), hsl(90,80%,55%), hsl(120,80%,55%), hsl(140,80%,55%))' }} />
            <span className="text-[9px] font-mono text-marble/30">BEARISH → BULLISH</span>
          </div>
          <div className="flex items-center gap-1.5">
            <span className="text-[9px] font-mono text-marble/20">Angle indicates projection slope</span>
          </div>
        </div>
      </div>

      <Footer />
    </div>
  );
};

export default LogRegistry;
